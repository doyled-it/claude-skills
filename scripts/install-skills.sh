#!/usr/bin/env bash
# Shared-skills fallback for runtimes without native plugins.
# Modern Claude Code and Codex should use agentic-dev-setup instead.
set -euo pipefail
MODE=symlink
while [ $# -gt 0 ]; do
  case "$1" in
    --copy) MODE=copy; shift ;;
    --help)
      echo 'Usage: bash scripts/install-skills.sh [--copy]'
      echo 'Fallback only: ~/.agents/skills is visible to multiple runtimes.'
      echo 'Native plugin setup: https://github.com/doyled-it/agentic-dev-setup'
      exit 0 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

# This shared path is also discovered by modern native-plugin runtimes. Avoid
# installing a second set there, even if the caller intends it for another tool.
for runtime in claude codex; do
  if command -v "$runtime" >/dev/null 2>&1 && "$runtime" plugin --help >/dev/null 2>&1; then
    echo "Native plugin support detected in $runtime; refusing shared skill links/copies." >&2
    echo 'Use https://github.com/doyled-it/agentic-dev-setup and remove old managed shared links before switching.' >&2
    exit 1
  fi
done

REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd)
TARGET="$HOME/.agents/skills"
link_one() {
  local src="$1" dest="$2"
  # Own only links this checkout installed to this exact skill. Preserve foreign
  # links (including dangling links), directories, and copied/manual skills.
  if [ -L "$dest" ]; then
    if [ "$(readlink "$dest")" != "$src" ]; then
      echo "  skip -> $dest (foreign symlink)"; return 0
    fi
    if [ "$MODE" = symlink ]; then return 0; fi
    rm -f "$dest"
  elif [ -e "$dest" ]; then
    echo "  skip -> $dest (existing file or directory)"; return 0
  fi
  mkdir -p "$(dirname "$dest")"
  if [ "$MODE" = copy ]; then
    cp -R "$src" "$dest"
    echo "  copied -> $dest"
  else
    ln -s "$src" "$dest"
    echo "  linked -> $dest"
  fi
}

# Remove only historical absolute links generated by this checkout, preserving
# real/manual skills and links into any other location.
for link in "$HOME/.claude/skills/"*; do
  [ -L "$link" ] || continue
  case "$(readlink "$link")" in
    "$REPO_ROOT"/plugins/*/skills/*) rm -f "$link" ;;
  esac
done

found=0
for skill_dir in "$REPO_ROOT"/plugins/*/skills/*/; do
  [ -f "$skill_dir/SKILL.md" ] || continue
  name=$(basename "$skill_dir")
  link_one "${skill_dir%/}" "$TARGET/$name"
  found=$((found + 1))
done
[ "$found" -gt 0 ] || { echo 'No skills found' >&2; exit 1; }
printf 'Processed %s skill(s) in %s. Install upstream Superpowers separately for this fallback runtime.\n' "$found" "$TARGET"
